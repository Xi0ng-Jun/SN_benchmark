#!/usr/bin/env bash
# Local services of the VeRO experiment: the LiteLLM proxy and the Wikipedia proxy.
#   experiments/vero/services.sh start|stop|status
# The LiteLLM configuration is generated from the VERO_*_MODEL / _API_BASE variables of env.sh into
# $VERO_STATE/litellm.yaml (keys stay in the environment: the file only names the variables).
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=env.sh
source "$HERE/env.sh" || exit 2
ROOT="$(cd "$HERE/../.." && pwd)"
STATE="$VERO_STATE"
mkdir -p "$STATE"

up() { curl -s -m 3 -o /dev/null "$1"; }

entry() {   # entry <alias> <ROLE>
  local model=VERO_$2_MODEL base=VERO_$2_API_BASE cap=VERO_$2_MAX_PARALLEL
  printf '  - model_name: %s\n    litellm_params:\n      model: %s\n      api_base: %s\n      api_key: os.environ/VERO_%s_API_KEY\n' \
    "$1" "${!model}" "${!base}" "$2"
  if [ -n "${!cap:-}" ]; then printf '      max_parallel_requests: %s\n' "${!cap}"; fi
}

config() {
  {
    echo "# Generated by experiments/vero/services.sh from the environment; do not edit."
    echo "model_list:"
    entry gpt-4.1-mini-2025-04-14 TARGET     # web_search_agent (SimpleQA)
    entry gpt-4.1-mini TARGET                # tau-bench agent and simulated user (Retail)
    entry gpt-4.1-2025-04-14 GRADER          # SimpleQA grader
    entry optimizer OPTIMIZER                # GEPA reflection model
    cat <<'YAML'
litellm_settings:
  drop_params: true          # parameters the upstream does not accept are dropped instead of failing the call
  request_timeout: 600
  num_retries: 3
general_settings:
  master_key: os.environ/LITELLM_API_KEY
YAML
  } > "$STATE/litellm.yaml"
}

start() {
  if up "http://127.0.0.1:$LITELLM_PORT/health/liveliness"; then echo "litellm: already up (stop first to apply a new model mapping)"; else
    command -v litellm >/dev/null || { echo "litellm not found: uv tool install 'litellm[proxy]'"; exit 2; }
    config
    setsid nohup litellm --config "$STATE/litellm.yaml" --port "$LITELLM_PORT" --host 127.0.0.1 \
      > "$STATE/litellm.log" 2>&1 < /dev/null & echo $! > "$STATE/litellm.pid"
    echo -n "litellm: starting"
    for _ in $(seq 1 180); do up "http://127.0.0.1:$LITELLM_PORT/health/liveliness" && break; echo -n .; sleep 1; done; echo
  fi
  if wiki_up; then echo "wiki proxy: already up"; else
    PYTHONPATH="$ROOT/src" setsid nohup "$VERO_PYTHON" -m rag_eval.vero.wiki_proxy \
      --port "$WIKI_PROXY_PORT" ${UPSTREAM_PROXY:+--upstream "$UPSTREAM_PROXY"} --cache "$STATE/wiki-cache.sqlite" \
      --rate "$WIKI_RATE" --user-agent "$WIKI_USER_AGENT" \
      > "$STATE/wiki-proxy.log" 2>&1 < /dev/null & echo $! > "$STATE/wiki-proxy.pid"
    sleep 2
  fi
  status
}

stop() {
  for name in litellm wiki-proxy; do
    if [ -f "$STATE/$name.pid" ]; then kill "$(cat "$STATE/$name.pid")" 2>/dev/null && echo "$name: stopped"; rm -f "$STATE/$name.pid"; fi
  done
}

# the wiki proxy answers 400 to a non-proxy request: any such answer means it is up
wiki_up() { curl -s -m 3 -o /dev/null -w "%{http_code}" "http://127.0.0.1:$WIKI_PROXY_PORT/" | grep -q 400; }

status() {
  local rc=0
  if up "http://127.0.0.1:$LITELLM_PORT/health/liveliness"; then
    echo "litellm: up (:$LITELLM_PORT) target=$VERO_TARGET_MODEL grader=$VERO_GRADER_MODEL optimizer=$VERO_OPTIMIZER_MODEL"
  else echo "litellm: DOWN"; rc=1; fi
  if wiki_up; then echo "wiki proxy: up (:$WIKI_PROXY_PORT) upstream=${UPSTREAM_PROXY:-direct}"; else echo "wiki proxy: DOWN"; rc=1; fi
  return $rc
}

case "${1:-status}" in start) start ;; stop) stop ;; status) status ;; *) echo "usage: $0 start|stop|status"; exit 2 ;; esac
