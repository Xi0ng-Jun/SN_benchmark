"""Pinned DeepEval Native templates, schemas, and scoring for expansion suites.

Imports are lazy. Preparation and bundle inspection only read source files;
request construction/scoring are explicit execution APIs for a later run.
"""
from __future__ import annotations

import ast
from pathlib import Path
import random
import re
from threading import Lock

from .artifacts import digest
from .public_expansion_protocol import EXPANSION_SUITES, EXPANSION_VERSION, native_protocol, normalize_answer
from .public_expansion_sources import make_expansion_case
from .starter_protocol import SDK_VERSION, fingerprint

_SUITE_MODULES = {
    "mmlu": "mmlu", "gsm8k": "gsm8k", "truthfulqa": "truthful_qa",
    "hellaswag": "hellaswag", "bbh": "big_bench_hard",
}
_TRUTHFULQA_RANDOM_LOCK = Lock()


def sdk_source_files(root: Path) -> list[Path]:
    """Include source and non-Python resources, excluding generated bytecode."""
    root = Path(root)
    files = [path for folder in ("benchmarks", "scorer")
             for path in (root / folder).rglob("*")
             if path.is_file() and "__pycache__" not in path.parts
             and path.suffix not in {".pyc", ".pyo"}]
    files.append(root / "utils.py")
    if any(not path.is_file() or not path.resolve().is_relative_to(root.resolve()) for path in files):
        raise ValueError("DeepEval source inventory contains missing files or paths outside the SDK")
    return sorted(set(files))


def required_sdk_paths(suite: str, cases=()) -> set[str]:
    """Minimum sources needed even when a manifest has been edited."""
    module = _SUITE_MODULES[suite]
    prefix = f"benchmarks/{module}"
    required = {"benchmarks/__init__.py", "benchmarks/schema.py", "scorer/__init__.py",
                "scorer/scorer.py", "utils.py", f"{prefix}/__init__.py",
                f"{prefix}/{module}.py", f"{prefix}/template.py"}
    if suite != "gsm8k":
        required.add(f"{prefix}/task.py")
    if suite == "truthfulqa":
        required.add(f"{prefix}/mode.py")
    if suite == "bbh":
        for folder in ("shot_prompts", "cot_prompts"):
            required.add(f"{prefix}/{folder}/__init__.py")
            required.update(f"{prefix}/{folder}/{case['task']}.txt" for case in cases)
    return required


def validate_sdk_snapshot(root: Path, manifest: dict, cases=()) -> None:
    """Validate source bytes and resource coverage without importing DeepEval."""
    root = Path(root).resolve()
    suite = manifest.get("suite")
    if suite not in EXPANSION_SUITES or manifest.get("deepeval_version") != SDK_VERSION:
        raise ValueError("Expansion requires a frozen DeepEval 4.2.2 source snapshot; reprepare the bundle")
    hashes = manifest.get("sdk_source_hashes")
    if not isinstance(hashes, dict) or not hashes:
        raise ValueError("Expansion requires nonempty frozen SDK source hashes; reprepare the bundle")
    required = required_sdk_paths(suite, cases)
    if not required <= hashes.keys():
        raise ValueError("Frozen SDK manifest omits required templates, schemas, scorer or prompt resources; reprepare the bundle")
    inventory = {str(path.relative_to(root)) for path in sdk_source_files(root)}
    if set(hashes) != inventory:
        raise ValueError("SDK source/resource inventory differs from frozen manifest; reprepare the bundle")
    for relative, expected in hashes.items():
        if not isinstance(relative, str) or not isinstance(expected, str) or not re.fullmatch(r"[0-9a-f]{64}", expected):
            raise ValueError("Invalid frozen SDK source hash")
        path = (root / relative).resolve()
        if not path.is_relative_to(root) or not path.is_file() or digest(path) != expected:
            raise ValueError("SDK source/resource changed: " + relative)


def validate_sdk_tasks(cases: list[dict], sdk_root: Path) -> None:
    """Read task enums statically so preparation never imports the SDK."""
    cache = {}
    for case in cases:
        suite = case["suite"]
        if suite not in {"mmlu", "hellaswag", "bbh"}:
            continue
        if suite not in cache:
            module = _SUITE_MODULES[suite]
            tree = ast.parse((Path(sdk_root) / f"benchmarks/{module}/task.py").read_text(encoding="utf-8"))
            values = set()
            for node in tree.body:
                if isinstance(node, ast.ClassDef):
                    for member in node.body:
                        if isinstance(member, ast.Assign) and isinstance(member.value, ast.Constant) and isinstance(member.value.value, str):
                            values.add(member.value.value)
            cache[suite] = values
        if case["task"] not in cache[suite]:
            raise ValueError(f"{suite} task is not in the pinned SDK enum: {case['task']}")


def _validate_case(case: dict, manifest: dict) -> None:
    suite = case.get("suite")
    if suite not in EXPANSION_SUITES or suite != manifest.get("suite"):
        raise ValueError("Expansion case suite differs from the manifest")
    if manifest.get("protocol_version") != EXPANSION_VERSION:
        raise ValueError("Incompatible expansion protocol; reprepare the local JSONL into a new directory")
    if manifest.get("release_gate") is not False:
        raise ValueError("Expansion bundles cannot enable an uncalibrated release gate")
    options = native_protocol(suite)
    if (manifest.get("native_protocol") != options or manifest.get("n_shots") != options["n_shots"]
            or manifest.get("scorer") != EXPANSION_SUITES[suite]["scorer"]
            or manifest.get("applicability") != EXPANSION_SUITES[suite]):
        raise ValueError("Expansion manifest settings differ from the fixed Native protocol")
    source = manifest.get("source", {})
    if not isinstance(source, dict) or case.get("source_file_sha256") != source.get("export_sha256"):
        raise ValueError("Expansion case source hash differs from the source export")
    canonical = make_expansion_case(
        suite, case["raw_row"], case["source_row_index"], revision=source["revision"],
        source_file_sha256=source["export_sha256"], source_line_sha256=case["source_line_sha256"],
    )
    if case != canonical:
        raise ValueError("Expansion case fields or references differ from its raw source row")
    identities = manifest.get("case_fingerprints")
    if not isinstance(identities, dict) or identities.get(case["case_id"]) != fingerprint(canonical):
        raise ValueError("Expansion case identity differs from the frozen manifest")


def build_request(case: dict, manifest: dict):
    """Return a canonical serializable request and the official SDK schema."""
    _validate_case(case, manifest)
    from .starter_native import check_sdk
    root = check_sdk(manifest)
    if not required_sdk_paths(case["suite"], [case]) <= manifest["sdk_source_hashes"].keys():
        raise ValueError("Frozen SDK manifest omits task prompt resources; reprepare the bundle")
    validate_sdk_tasks([case], root)
    from deepeval.benchmarks import schema as schemas

    suite, row, task = case["suite"], case["raw_row"], case["task"]
    if suite == "mmlu":
        from deepeval.benchmarks.mmlu.template import MMLUTemplate as template
        from deepeval.benchmarks.mmlu.task import MMLUTask
        native_input = template.format_question(row, include_answer=False)
        prompt = template.generate_output(input=native_input, train_set=[], task=MMLUTask(task), n_shots=0)
        expected = "ABCD"[row["answer"]]
        schema = schemas.MultipleChoiceSchema
    elif suite == "gsm8k":
        from deepeval.benchmarks.gsm8k.template import GSM8KTemplate as template
        native_input, expected = row["question"], template.format_answer(row)
        prompt = template.generate_output(input=native_input, train_set=[], n_shots=0, enable_cot=False)
        schema = schemas.NumberSchema
    elif suite == "truthfulqa":
        from deepeval.benchmarks.truthful_qa.template import TruthfulQATemplate as template
        from deepeval.benchmarks.truthful_qa.mode import TruthfulQAMode
        # The official template seeds the process RNG. Restore its state after
        # using the actual SDK formatter; local source conversion uses Random(42).
        with _TRUTHFULQA_RANDOM_LOCK:
            state = random.getstate()
            try:
                native_input, expected = template.format_mc1_question(row, seed=42)
            finally:
                random.setstate(state)
        prompt = template.generate_output(input=native_input, mode=TruthfulQAMode.MC1)
        schema = schemas.NumberSchema
    elif suite == "hellaswag":
        from deepeval.benchmarks.hellaswag.template import HellaSwagTemplate as template
        from deepeval.benchmarks.hellaswag.task import HellaSwagTask
        native_input = template.format_question(row, include_answer=False)
        prompt = template.generate_output(input=native_input, train_set=[], task=HellaSwagTask(task), n_shots=0)
        expected, schema = "ABCD"[int(row["label"])], schemas.MultipleChoiceSchema
    else:
        from deepeval.benchmarks.big_bench_hard.template import BigBenchHardTemplate as template
        from deepeval.benchmarks.big_bench_hard.task import BigBenchHardTask
        native_input, expected = row["input"], row["target"]
        prompt = template.generate_output(input=native_input, task=BigBenchHardTask(task), n_shots=0, enable_cot=False)
        schema = schemas.bbh_models_dict[task]
    if expected != case["expected_answer"] or case["references"] != [expected]:
        raise ValueError("SDK answer conversion differs from the frozen source conversion")
    request = {
        "protocol_version": EXPANSION_VERSION, "track": "N", "suite": suite,
        "case_id": case["case_id"], "sample_id": case["sample_id"], "task": task,
        "native_input": native_input, "prompt": prompt, "expected_output": expected,
        "schema": schema.model_json_schema(), "schema_name": schema.__name__,
        "n_shots": case["n_shots"], "native_protocol": native_protocol(suite),
        "scorer": case["scorer"], "sdk_identity": fingerprint(manifest["sdk_source_hashes"]),
        "case_identity": fingerprint(case),
    }
    return request, schema


def score_prediction(case: dict, request: dict, prediction: str, manifest: dict) -> dict:
    """Use the SDK scorer on the saved schema answer, without recovery parsing."""
    if not isinstance(prediction, str):
        raise ValueError("Prediction must be the schema-parsed answer serialized as text")
    rebuilt, _ = build_request(case, manifest)
    if request != rebuilt:
        raise ValueError("Prediction request does not match the frozen Native protocol")
    from deepeval.scorer import Scorer
    value = Scorer.exact_match_score(request["expected_output"], prediction)
    if value not in (0, 1):
        raise ValueError("Native binary scorer returned a value other than 0 or 1")
    return {
        "status": "scored", "score": float(value), "score_kind": "official_native",
        "scorer": case["scorer"], "raw_answer": prediction,
        "normalization": normalize_answer(case["suite"], prediction, task=case["task"]),
        "limitations": case["limitations"],
    }
