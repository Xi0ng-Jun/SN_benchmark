// Uses collaboration-server.py's temporary SQLite and synthetic bridge. The
// browser/UI, HTTP scope, source reread, persistence and revisions are real.
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const url = process.env.WORKBENCH_TEST_URL;
assert(url, 'A dedicated test-state URL is required');
const browser = await chromium.launch({ headless: true, executablePath: process.env.WORKBENCH_CHROMIUM });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const failures = [];
page.on('pageerror', error => failures.push(String(error)));
try {
  await page.goto(url);
  await page.getByTestId('new-task').waitFor();
  const previous = await page.evaluate(() => new URLSearchParams(location.hash.slice(1)).get('task'));
  await page.getByTestId('new-task').click();
  await page.getByTestId('task-title').fill('有出处候选与人工判断独立验收');
  await page.getByTestId('create-task').click();
  await page.waitForFunction(old => new URLSearchParams(location.hash.slice(1)).get('task') !== old, previous);
  await page.getByTestId('task-composer').waitFor();
  assert.equal(await page.getByTestId('candidate-records-panel').count(), 1);
  const task = await page.evaluate(() => new URLSearchParams(location.hash.slice(1)).get('task'));
  const panel = page.getByTestId('task-session-panel');
  for (const agent of ['candidate-agent-A', 'candidate-agent-B']) {
    await page.getByTestId('session-agent-id-input').fill(agent);
    await page.getByTestId('session-link').click();
    await panel.getByRole('button', { name: new RegExp('选择已保存会话.*' + agent) }).waitFor();
  }
  const choose = agent => panel.getByRole('button', { name: new RegExp('选择已保存会话.*' + agent) }).click();
  const extract = kind => panel.getByRole('button', { name: new RegExp('提取' + kind + '候选') });
  await choose('candidate-agent-A');
  await page.getByTestId('session-refresh').click();
  await extract('发现').waitFor();
  await extract('发现').click();
  await page.getByTestId('candidate-draft-panel').waitFor();
  const original = '  模型原文\n独立保存  ';
  assert.equal(await page.getByTestId('candidate-source-text').innerText(), original);
  assert.equal(await page.getByTestId('candidate-save').isEnabled(), false);
  await page.getByTestId('candidate-text').fill('人工选取的候选内容');
  await page.getByTestId('session-refresh').click();
  await panel.getByText(original, { exact: true }).waitFor();
  assert.equal(await page.getByTestId('candidate-save').isEnabled(), false, 'new read generation invalidates the open source binding');
  assert.equal(await page.getByTestId('candidate-text').inputValue(), '人工选取的候选内容');
  await page.getByTestId('candidate-cancel').click();
  await extract('发现').click();
  await page.getByTestId('candidate-text').fill('迟到候选A');
  let held;
  let savedA;
  let markSaved;
  const savedReady = new Promise(resolve => { markSaved = resolve; });
  const bodies = [];
  await page.route('**/api/tasks/' + task + '/sessions/*/candidates', async route => {
    bodies.push(route.request().postDataJSON());
    const response = await route.fetch();
    savedA = await response.json(); held = { route, response }; markSaved();
  });
  await page.getByTestId('candidate-save').click();
  await savedReady;
  await page.waitForFunction(() => document.querySelector('[data-testid="candidate-text"]')?.readOnly === true);
  await choose('candidate-agent-B');
  await page.getByTestId('candidate-cancel').click();
  await page.getByTestId('session-refresh').click();
  await extract('方向').click();
  await page.getByTestId('candidate-text').fill('B的新候选草稿');
  assert.equal(await page.getByTestId('candidate-save').isEnabled(), true);
  await held.route.fulfill({ response: held.response });
  assert.equal(await page.getByTestId('candidate-text').inputValue(), 'B的新候选草稿');
  assert.equal(await page.getByTestId('candidate-draft-panel').getByText('候选已保存', { exact: true }).count(), 0);
  assert.deepEqual(Object.keys(bodies[0]).sort(), ['kind', 'locator', 'request_key', 'text']);
  assert.equal(savedA.source.text, original);
  await page.unroute('**/api/tasks/' + task + '/sessions/*/candidates');
  await page.getByTestId('candidate-records-refresh').click();
  await page.getByTestId('candidate-record-' + savedA.id).click();
  assert.equal(await page.getByTestId('candidate-record-source-text').innerText(), original);
  assert.equal(await page.getByTestId('candidate-decision-save').isEnabled(), false);
  await page.getByTestId('candidate-judgment-confirmed').click();
  await page.getByTestId('candidate-decision-reason').fill('  独立人工核对理由  ');
  await page.getByTestId('candidate-decision-save').click();
  await page.waitForFunction(() => document.querySelector('[data-testid="candidate-decision-receipt"]')?.textContent?.includes('人工判断已保存'));
  let records = await page.evaluate(async id => (await (await fetch('/api/tasks/' + id + '/candidates')).json()), task);
  const ownHead = records[0].decisions[0].id;
  assert.equal(records[0].decisions[0].reason, '独立人工核对理由');
  // A different actor's later visible revision must never replace alice's
  // optimistic concurrency baseline for the next actual POST.
  await page.route('**/api/tasks/' + task + '/candidates', async route => {
    const response = await route.fetch(); const list = await response.json();
    const other = { id: 'bob-head', candidate_id: savedA.id, actor: 'bob', judgment: 'rejected', reason: '另一操作者',
      saved_at: '2026-10-11T01:00:00Z', parent_id: null, base_revision: null };
    list[0].decisions.push(other); list[0].decision = other;
    await route.fulfill({ json: list });
  });
  await page.getByTestId('candidate-records-refresh').click();
  await page.getByTestId('candidate-records-panel').getByText('另一操作者', { exact: true }).waitFor();
  const decisionBodies = [];
  await page.route('**/api/tasks/' + task + '/candidates/' + savedA.id + '/decisions', async route => {
    decisionBodies.push(route.request().postDataJSON()); await route.continue();
  });
  await page.getByTestId('candidate-judgment-rejected').click();
  await page.getByTestId('candidate-decision-reason').fill('修订人工判断');
  assert.equal(await page.getByTestId('candidate-decision-receipt').getByText(/人工判断已保存/).count(), 0);
  await page.getByTestId('candidate-decision-save').click();
  await page.waitForFunction(() => document.querySelector('[data-testid="candidate-decision-receipt"]')?.textContent?.includes('人工判断已保存'));
  assert.equal(decisionBodies[0].base_revision, ownHead);
  assert.deepEqual(Object.keys(decisionBodies[0]).sort(), ['base_revision', 'judgment', 'reason', 'request_key']);
  await page.unroute('**/api/tasks/' + task + '/candidates');
  records = await page.evaluate(async id => (await (await fetch('/api/tasks/' + id + '/candidates')).json()), task);
  assert.equal(records[0].decisions.length, 2);
  assert.equal(records[0].source.text, original);
  // The real server commits B, then the browser loses the response. A write
  // transport error must remain unknown and must not enable a fresh key retry.
  await page.route('**/api/tasks/' + task + '/sessions/*/candidates', async route => { await route.fetch(); await route.abort(); });
  await page.getByTestId('candidate-save').click();
  await page.getByTestId('candidate-draft-panel').getByText(/保存回执未知/).waitFor();
  assert.equal(await page.getByTestId('candidate-save').isEnabled(), false);
  assert.equal(await page.getByTestId('candidate-text').isEditable(), false);
  records = await page.evaluate(async id => (await (await fetch('/api/tasks/' + id + '/candidates')).json()), task);
  assert.equal(records.length, 2);
  assert.equal(records[1].decision, null, 'model candidate storage does not create human judgment');
  await page.unroute('**/api/tasks/' + task + '/sessions/*/candidates');
  await page.route('**/api/tasks/' + task + '/sessions/*/candidate-receipt', route => route.fulfill({ json: { status: 'missing' } }));
  await page.getByTestId('candidate-check-receipt').click();
  await page.getByTestId('candidate-draft-panel').getByText(/尚未找到已提交回执/).waitFor();
  assert.equal(await page.getByTestId('candidate-save').isEnabled(), false, 'missing receipt does not prove the original write stopped');
  assert.equal(await page.getByTestId('candidate-text').isEditable(), false);
  await page.unroute('**/api/tasks/' + task + '/sessions/*/candidate-receipt');
  await page.getByTestId('candidate-check-receipt').click();
  await page.getByTestId('candidate-draft-panel').getByText('候选已保存', { exact: true }).waitFor();
  records = await page.evaluate(async id => (await (await fetch('/api/tasks/' + id + '/candidates')).json()), task);
  assert.equal(records.length, 2, 'receipt reconciliation executes no new save');
  await page.getByTestId('candidate-record-' + savedA.id).click();
  await page.getByTestId('candidate-judgment-undecided').click();
  await page.getByTestId('candidate-decision-reason').fill('丢回执后的独立人工判断');
  await page.unroute('**/api/tasks/' + task + '/candidates/' + savedA.id + '/decisions');
  await page.route('**/api/tasks/' + task + '/candidates/' + savedA.id + '/decisions', async route => { await route.fetch(); await route.abort(); });
  await page.getByTestId('candidate-decision-save').click();
  await page.getByTestId('candidate-records-panel').getByText(/保存结果未知，请先核对/).waitFor();
  assert.equal(await page.getByTestId('candidate-decision-save').isEnabled(), false);
  let decisionReply;
  let markDecisionReply;
  const decisionReplyReady = new Promise(resolve => { markDecisionReply = resolve; });
  await page.route('**/api/tasks/' + task + '/candidates/' + savedA.id + '/decision-receipt', async route => {
    decisionReply = { route, response: await route.fetch() }; markDecisionReply();
  });
  await page.getByTestId('candidate-decision-check-receipt').click();
  await decisionReplyReady;
  await page.getByTestId('candidate-record-' + records[1].id).click();
  await page.getByTestId('candidate-judgment-rejected').click();
  await page.getByTestId('candidate-decision-reason').fill('另一候选的未提交判断');
  await decisionReply.route.fulfill({ response: decisionReply.response });
  assert.equal(await page.getByTestId('candidate-decision-reason').inputValue(), '另一候选的未提交判断');
  assert.doesNotMatch(await page.getByTestId('candidate-decision-receipt').innerText(), /人工判断已保存/);
  await page.getByTestId('candidate-record-' + savedA.id).click();
  await page.waitForFunction(() => document.querySelector('[data-testid="candidate-decision-receipt"]')?.textContent?.includes('人工判断已保存'));
  records = await page.evaluate(async id => (await (await fetch('/api/tasks/' + id + '/candidates')).json()), task);
  assert.equal(records[0].decisions.length, 3, 'decision reconciliation executes no new judgment');
  await page.getByTestId('theme-toggle').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
  assert.deepEqual(failures, []);
  console.log('Candidate parent checks passed: actual scoped reread/storage, source invalidation, late replies, per-actor head, human revisions and unknown prevention');
} finally { await browser.close(); }
